export function getFilmGuide(skill: Pick<SkillManifest, 'source' | 'slug'>) {
  return skill.source === 'official' && Object.hasOwn(filmGuides, skill.slug) ? filmGuides[skill.slug] : undefined
}

export function getSkillGuide(skill: SkillManifest): SkillGuide {
  return getFilmGuide(skill) ?? (skill.source === 'official' && Object.hasOwn(builtinGuides, skill.slug) ? builtinGuides[skill.slug] : {
    intro: skill.description,
    inputs: [[skill.parameters.find((field) => field.bind === 'prompt')?.label ?? '本次任务', '说明要完成的内容或提供参考素材。', '填写目标、约束与输出要求']],
    optional: skill.parameters.filter((field) => field.bind !== 'prompt').map((field) => field.label).join('、') || '参考素材与输出约束。',
    example: '根据提供的素材完成本次任务，并保留关键限制。',
    steps: [['明确输入', '填写任务及适用的参数。'], ['确认并执行', '按 Skill 定义执行，完成后查看节点结果。']],
    rules: ['按当前任务与素材确定输出。'],
  })
}
